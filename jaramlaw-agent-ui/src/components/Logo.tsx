/** 자람법 로고 — 한글 워드마크.
 *
 * 이전 로고(녹색 둥근 타일 + 흰 stroke 새싹)를 버렸다. 국내 육아·보육 서비스
 * 헤더 8곳을 실제로 캡처해 보니(자란다·아이사랑·맘큐·몽땅정보통·키즈노트·째깍악어·
 * 아이돌봄·차이의놀이) 결론이 세 줄로 나왔다:
 *
 *   ① "둥근 사각 타일 + 흰 stroke 아이콘"을 쓰는 곳이 0곳이다.
 *      그건 SaaS·개발자도구 관례(Linear/Notion/Vercel)지 육아 서비스의 언어가 아니다.
 *   ② 8곳 중 4곳은 심볼이 아예 없다 — 글자 자체가 로고다.
 *   ③ 은유가 0건이다. 자란다에 새싹 없고, 아이사랑에 하트 없고, 맘큐에 아기 없다.
 *
 * 앞선 심볼은 "자람=새싹, 법=기준선"으로 **이름을 그림으로 직역**한 것이었다.
 * 직역이야말로 이 카테고리에서 아무도 하지 않는 짓이고, 그래서 지어낸 티가 났다.
 *
 * 그래서 은유를 전부 걷어내고 이름만 남긴다. 개입은 하나뿐 — 의미 단위에서
 * 색을 끊는다(`자람` / `법`). 자란다가 글자마다 색을 바꾸고 맘큐가 Q만 대문자로
 * 두는 것과 같은 종류의, 최소한의 손질이다.
 */

/** 헤더 로고 — 워드마크 + 태그라인. 타일 없음. */
export function BrandLock({ tagline = "가족 법령·정책 안내" }: { tagline?: string }) {
  return (
    <span className="brand-word">
      <strong className="brand-mark">
        자람<span className="brand-mark-accent">법</span>
      </strong>
      <small>{tagline}</small>
    </span>
  );
}
